"""Build a combined training list: India train + Japan D10 images (+ optional D10 repeats).

Ultralytics reads a .txt list of image paths and keeps duplicate lines, so repeating a path
oversamples that image. Val and test stay India-only so results compare with the baseline.

Examples:
    python src/make_trainset.py --india data/rdd4 --japan data/japan_d10 --name rdd4_jp
    python src/make_trainset.py --india data/rdd4_gde --japan data/japan_d10_gde --name rdd4_gde_jp --d10-repeat 2
"""
import argparse
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
D10 = 1


def classes_in(img: Path) -> list[int]:
    lbl = img.parent.parent / "labels" / f"{img.stem}.txt"
    return [int(l.split()[0]) for l in lbl.read_text().splitlines() if l.strip()] if lbl.exists() else []


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--india", required=True, help="India dataset root with train/val/test")
    ap.add_argument("--japan", required=True, help="Japan D10 dataset root with images/ and labels/")
    ap.add_argument("--name", required=True, help="writes configs/<name>_train.txt and configs/<name>.yaml")
    ap.add_argument("--d10-repeat", type=int, default=1, help="total copies of each India image containing D10")
    args = ap.parse_args()

    india, japan = Path(args.india).resolve(), Path(args.japan).resolve()
    lines, boxes, n_india, n_japan = [], Counter(), 0, 0
    for img in sorted((india / "train" / "images").glob("*.jpg")):
        cls = classes_in(img)
        copies = args.d10_repeat if D10 in cls else 1
        lines += [img.as_posix()] * copies
        boxes.update(cls * copies)
        n_india += copies
    for img in sorted((japan / "images").glob("*.jpg")):
        lines.append(img.as_posix())
        boxes.update(classes_in(img))
        n_japan += 1

    txt = ROOT / "configs" / f"{args.name}_train.txt"
    txt.write_text("\n".join(lines) + "\n")
    base = yaml.safe_load((ROOT / "configs" / "rdd4.yaml").read_text())
    cfg = {"path": india.as_posix(), "train": txt.as_posix(), "val": "val/images", "test": "test/images",
           "names": base["names"]}
    (ROOT / "configs" / f"{args.name}.yaml").write_text(
        f"# India ({india.name}) + Japan D10 ({japan.name}); val/test India only. Generated by src/make_trainset.py\n"
        + yaml.safe_dump(cfg, sort_keys=False))

    total = sum(boxes.values())
    print(f"Train list: {len(lines)} images ({n_india} India incl. repeats, {n_japan} Japan) -> {txt}")
    for c, n in enumerate(base["names"].values()):
        print(f"  {n:24s} {boxes[c]:6d} boxes ({boxes[c] / total:.1%})")
    print(f"Config: configs/{args.name}.yaml")


if __name__ == "__main__":
    main()
