"""Split the Japan D10 images into train/val/test and merge them into the India splits.

Japan images are split in blocks of consecutive image IDs (--group), not one by one:
neighbouring IDs are often consecutive photos of the same road, and splitting them
individually would leak near-duplicates from train into val/test.

The split assignment is saved (configs/japan_d10_split.json) and reused, so raw and
guided-filter variants get the same split. Files are hard-linked (no extra disk space).

Outputs:
    <dst>/{train,val,test}/{images,labels}         India + Japan (for training)
    <japan-dst>/{train,val,test}/{images,labels}   Japan only (for Japan-only scores)
    configs/<dst name>.yaml, configs/<japan-dst name>.yaml

Examples:
    python src/merge_japan_split.py                       # guided-filter variant (default)
    python src/merge_japan_split.py --india data/rdd4 --japan data/japan_d10 --dst data/india_japan --japan-dst data/japan_d10_split
"""
import argparse
import json
import os
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPLITS = ["train", "val", "test"]
NAMES = ["D00", "D10", "D20", "D40"]


def link(src: Path, dst: Path) -> None:
    if dst.exists():
        return
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def assign_splits(stems: list[str], ratios: list[float], group: int, seed: int) -> dict[str, str]:
    """Assign whole ID blocks to splits, filling the split furthest below its target first."""
    blocks = defaultdict(list)
    for s in stems:
        blocks[int(s.split("_")[-1]) // group].append(s)
    keys = sorted(blocks)
    random.Random(seed).shuffle(keys)
    target = {sp: r * len(stems) for sp, r in zip(SPLITS, ratios)}
    count = Counter()
    out = {}
    for k in keys:
        sp = max(SPLITS, key=lambda x: target[x] - count[x])
        for s in blocks[k]:
            out[s] = sp
        count[sp] += len(blocks[k])
    return out


def write_yaml(path: Path, root: Path, note: str) -> None:
    names = yaml.safe_load((ROOT / "configs" / "rdd4.yaml").read_text())["names"]
    cfg = {"path": root.resolve().as_posix(), "train": "train/images", "val": "val/images",
           "test": "test/images", "names": names}
    path.write_text(f"# {note}. Generated by src/merge_japan_split.py\n" + yaml.safe_dump(cfg, sort_keys=False))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--india", default=str(ROOT / "data" / "rdd4_gde"))
    ap.add_argument("--japan", default=str(ROOT / "data" / "japan_d10_gde"))
    ap.add_argument("--dst", default=str(ROOT / "data" / "india_japan_gde"))
    ap.add_argument("--japan-dst", default=str(ROOT / "data" / "japan_d10_gde_split"))
    ap.add_argument("--ratios", type=float, nargs=3, default=[0.70, 0.15, 0.15], help="train val test")
    ap.add_argument("--group", type=int, default=50, help="block size in image IDs")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--split-file", default=str(ROOT / "configs" / "japan_d10_split.json"))
    args = ap.parse_args()

    india, japan = Path(args.india), Path(args.japan)
    dst, jdst = Path(args.dst), Path(args.japan_dst)
    stems = sorted(p.stem for p in (japan / "images").glob("*.jpg"))

    split_file = Path(args.split_file)
    if split_file.exists():
        assignment = json.loads(split_file.read_text())
        missing = set(stems) - set(assignment)
        if missing:
            raise SystemExit(f"{split_file} does not cover {len(missing)} Japan images; delete it to re-split")
        print(f"Reusing split from {split_file}")
    else:
        assignment = assign_splits(stems, args.ratios, args.group, args.seed)
        split_file.write_text(json.dumps(assignment, indent=0, sort_keys=True))
        print(f"New split (blocks of {args.group} IDs, seed {args.seed}) saved to {split_file}")

    stats = {sp: {"india": 0, "japan": 0, "boxes": Counter(), "jp_boxes": Counter()} for sp in SPLITS}
    for sp in SPLITS:
        for d in (dst / sp / "images", dst / sp / "labels", jdst / sp / "images", jdst / sp / "labels"):
            d.mkdir(parents=True, exist_ok=True)
        for img in (india / sp / "images").glob("*.jpg"):
            lbl = india / sp / "labels" / f"{img.stem}.txt"
            link(img, dst / sp / "images" / img.name)
            link(lbl, dst / sp / "labels" / lbl.name)
            stats[sp]["india"] += 1
            stats[sp]["boxes"].update(int(l.split()[0]) for l in lbl.read_text().splitlines() if l.strip())
    for stem in stems:
        sp = assignment[stem]
        img, lbl = japan / "images" / f"{stem}.jpg", japan / "labels" / f"{stem}.txt"
        for root in (dst, jdst):
            link(img, root / sp / "images" / img.name)
            link(lbl, root / sp / "labels" / lbl.name)
        stats[sp]["japan"] += 1
        cls = [int(l.split()[0]) for l in lbl.read_text().splitlines() if l.strip()]
        stats[sp]["boxes"].update(cls)
        stats[sp]["jp_boxes"].update(cls)

    write_yaml(ROOT / "configs" / f"{dst.name}.yaml", dst, f"India ({india.name}) + Japan D10 split ({japan.name})")
    write_yaml(ROOT / "configs" / f"{jdst.name}.yaml", jdst, f"Japan D10 only ({japan.name}), same split")

    print(f"\n{'split':6s} {'India':>6s} {'Japan':>6s} {'total':>6s}  " + "  ".join(f"{n:>11s}" for n in NAMES))
    for sp in SPLITS:
        s = stats[sp]
        per = "  ".join(f"{s['boxes'][c]:5d} ({s['jp_boxes'][c]:4d})" for c in range(4))
        print(f"{sp:6s} {s['india']:6d} {s['japan']:6d} {s['india'] + s['japan']:6d}  {per}")
    print("(boxes per class: total (from Japan))")
    print(f"\nCombined: {dst}  -> configs/{dst.name}.yaml")
    print(f"Japan only: {jdst}  -> configs/{jdst.name}.yaml")


if __name__ == "__main__":
    main()
