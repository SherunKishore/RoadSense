"""Build RDD-China (ChinaDrone + ChinaMotorBike) as in the base paper (BSW-YOLO, Wang et al. 2026).

Keeps every train image with at least one D00/D10/D20/D40 box (drops "Repair" / "Block crack"),
which gives the paper's 3853 images / 7718 boxes. Converts Pascal VOC XML -> YOLO txt with the
same verified converter as the Japan data (add_japan_d10.voc_to_yolo).

Two 8:1:1 splits (hard links, no extra disk space):
  data/rdd_china        paper-style random split (seed 0) -> like-for-like comparison with the paper
  data/rdd_china_block  leak-free split in blocks of consecutive image IDs (per source), since
                        ChinaMotorBike frames come from continuous rides

Example:
    python src/add_china.py --sheet china_crops
"""
import argparse
import io
import os
import random
import shutil
import xml.etree.ElementTree as ET
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

import yaml
from PIL import Image

from add_japan_d10 import crop_sheet, voc_to_yolo

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [("RDD2022_China_Drone.zip", "China_Drone"), ("RDD2022_China_MotorBike.zip", "China_MotorBike")]
NAMES = ["D00", "D10", "D20", "D40"]
SPLITS = ["train", "val", "test"]
RATIOS = [0.8, 0.1, 0.1]


def link(src: Path, dst: Path) -> None:
    if not dst.exists():
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)


def random_split(stems, seed):
    s = sorted(stems)
    random.Random(seed).shuffle(s)
    n_tr, n_va = round(RATIOS[0] * len(s)), round(RATIOS[1] * len(s))
    return {x: ("train" if i < n_tr else "val" if i < n_tr + n_va else "test") for i, x in enumerate(s)}


def block_split(stems, group, seed):
    """Whole blocks of consecutive IDs (per source) go to one split; fill the split furthest below target."""
    blocks = defaultdict(list)
    for x in stems:
        src, num = x.rsplit("_", 1)
        blocks[(src, int(num) // group)].append(x)
    keys = sorted(blocks)
    random.Random(seed).shuffle(keys)
    target = {sp: r * len(stems) for sp, r in zip(SPLITS, RATIOS)}
    count, out = Counter(), {}
    for k in keys:
        sp = max(SPLITS, key=lambda s: target[s] - count[s])
        for x in blocks[k]:
            out[x] = sp
        count[sp] += len(blocks[k])
    return out


def materialise(all_dir: Path, dst: Path, assignment: dict) -> dict:
    stats = {sp: Counter() for sp in SPLITS}
    for sp in SPLITS:
        (dst / sp / "images").mkdir(parents=True, exist_ok=True)
        (dst / sp / "labels").mkdir(parents=True, exist_ok=True)
    for stem, sp in assignment.items():
        link(all_dir / "images" / f"{stem}.jpg", dst / sp / "images" / f"{stem}.jpg")
        lbl = all_dir / "labels" / f"{stem}.txt"
        link(lbl, dst / sp / "labels" / f"{stem}.txt")
        stats[sp]["images"] += 1
        stats[sp].update(NAMES[int(l.split()[0])] for l in lbl.read_text().splitlines() if l.strip())
    names = yaml.safe_load((ROOT / "configs" / "rdd4.yaml").read_text())["names"]
    cfg = {"path": dst.resolve().as_posix(), "train": "train/images", "val": "val/images", "test": "test/images",
           "names": names}
    (ROOT / "configs" / f"{dst.name}.yaml").write_text(
        f"# RDD-China ({dst.name}), 8:1:1. Generated by src/add_china.py\n" + yaml.safe_dump(cfg, sort_keys=False))
    return stats


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--group", type=int, default=50, help="block size in image IDs for the leak-free split")
    ap.add_argument("--sheet", default=None, help="write per-class crop sheets <sheet>_D00.jpg ... for a visual check")
    args = ap.parse_args()

    all_dir = ROOT / "data" / "china_all"
    (all_dir / "images").mkdir(parents=True, exist_ok=True)
    (all_dir / "labels").mkdir(parents=True, exist_ok=True)
    kept, dropped_imgs, boxes, dropped_cls, skipped = [], 0, Counter(), Counter(), 0
    for zname, sub in SOURCES:
        zf = zipfile.ZipFile(ROOT / "downloads" / zname)
        for x in sorted(n for n in zf.namelist() if n.startswith(f"{sub}/train/annotations/xmls/") and n.endswith(".xml")):
            stem = Path(x).stem
            img_bytes = zf.read(f"{sub}/train/images/{stem}.jpg")
            w, h = Image.open(io.BytesIO(img_bytes)).size
            lines, bxs, sk, dr = voc_to_yolo(zf.read(x), img_size=(w, h))
            skipped += sk
            dropped_cls += dr
            if not lines:
                dropped_imgs += 1
                continue
            (all_dir / "images" / f"{stem}.jpg").write_bytes(img_bytes)
            (all_dir / "labels" / f"{stem}.txt").write_text("\n".join(lines) + "\n")
            boxes.update(NAMES[b[0]] for b in bxs)
            kept.append(stem)
    print(f"Kept {len(kept)} images with >=1 D00/D10/D20/D40 box (paper: 3853); dropped {dropped_imgs} without")
    print(f"Boxes: {dict(boxes)} total {sum(boxes.values())} (paper: 7718) | other classes dropped: {dict(dropped_cls)}"
          f" | malformed skipped: {skipped}")

    for name, assignment in (("rdd_china", random_split(kept, args.seed)),
                             ("rdd_china_block", block_split(kept, args.group, args.seed))):
        stats = materialise(all_dir, ROOT / "data" / name, assignment)
        print(f"\n{name}:  " + "  ".join(f"{sp} {stats[sp]['images']}" for sp in SPLITS))
        for sp in SPLITS:
            print(f"   {sp:5s} " + "  ".join(f"{n} {stats[sp][n]:5d}" for n in NAMES))
        print(f"   config: configs/{name}.yaml")

    if args.sheet:
        for c, n in enumerate(NAMES):
            out = f"{args.sheet}_{n}.jpg"
            crop_sheet(all_dir, Path(out), cls=c)
            print(f"crop sheet: {out}")


if __name__ == "__main__":
    main()
