"""Module 0 - Build the 4-class RDD dataset from RDD_SPLIT.

Keeps the four RDD2022 damage classes (D00, D10, D20, D40) and drops road-marking wear.
Images left with no boxes become background images.

RDD_SPLIT has ids 3 and 4 swapped (verified by inspecting box crops):
  id 3 "D40_Pothole" -> actually faded lane markings / crosswalks  -> dropped
  id 4 "D44_Other"   -> actually potholes (3187 boxes, the official India D40 count) -> becomes id 3
Ids 0-2 (D00, D10, D20) are correct and kept as-is.

Images are hard-linked (no extra disk space). RDD_SPLIT is never modified.
"""
import argparse
import os
import shutil
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "RDD_SPLIT"
DST = ROOT / "data" / "rdd4"
CFG = ROOT / "configs" / "rdd4.yaml"

REMAP = {0: 0, 1: 1, 2: 2, 4: 3}  # source id -> output id; source id 3 (lane markings) is dropped
NAMES = ["D00_Longitudinal_Crack", "D10_Transverse_Crack", "D20_Alligator_Crack", "D40_Pothole"]
SPLITS = ["train", "val", "test"]


def link_or_copy(src: Path, dst: Path) -> None:
    if dst.exists():
        return
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def build_split(split: str) -> dict:
    s_img, s_lbl = SRC / split / "images", SRC / split / "labels"
    d_img, d_lbl = DST / split / "images", DST / split / "labels"
    d_img.mkdir(parents=True, exist_ok=True)
    d_lbl.mkdir(parents=True, exist_ok=True)

    boxes, imgs_with = Counter(), Counter()
    dropped = background = 0
    images = sorted(p for p in s_img.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    for img in images:
        link_or_copy(img, d_img / img.name)
        lbl = s_lbl / f"{img.stem}.txt"
        lines = lbl.read_text().splitlines() if lbl.exists() else []
        kept = []
        for line in lines:
            parts = line.split()
            if len(parts) != 5:
                continue
            src = int(parts[0])
            if src in REMAP:
                c = REMAP[src]
                kept.append(" ".join([str(c), *parts[1:]]))
                boxes[c] += 1
            else:
                dropped += 1
        for c in {int(k.split()[0]) for k in kept}:
            imgs_with[c] += 1
        if not kept:
            background += 1
        (d_lbl / f"{img.stem}.txt").write_text("\n".join(kept) + ("\n" if kept else ""))

    return {"images": len(images), "background": background, "dropped": dropped,
            "boxes": boxes, "imgs_with": imgs_with}


def write_yaml() -> None:
    CFG.parent.mkdir(parents=True, exist_ok=True)
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(NAMES))
    CFG.write_text(
        "# RDD2022 India - 4 damage classes (lane markings removed, pothole id fixed). Generated by src/prepare_data.py\n"
        f"path: {DST.as_posix()}\n"
        "train: train/images\n"
        "val: val/images\n"
        "test: test/images\n\n"
        f"names:\n{names}\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--force", action="store_true", help="delete data/rdd4 and rebuild")
    args = ap.parse_args()

    if not SRC.exists():
        raise SystemExit(f"Source dataset not found: {SRC}")
    if args.force and DST.exists():
        shutil.rmtree(DST)

    print(f"{'split':6s} {'images':>7s} {'backgr':>7s} {'dropped':>8s}  " +
          "  ".join(f"{n[:3]:>11s}" for n in NAMES))
    for split in SPLITS:
        r = build_split(split)
        per_cls = "  ".join(f"{r['boxes'][i]:5d}/{r['imgs_with'][i]:<5d}" for i in range(len(NAMES)))
        print(f"{split:6s} {r['images']:7d} {r['background']:7d} {r['dropped']:8d}  {per_cls}")
    print("(per class: boxes/images; dropped = lane-marking boxes, source id 3)")

    write_yaml()
    print(f"\nDataset: {DST}\nConfig:  {CFG}")


if __name__ == "__main__":
    main()
